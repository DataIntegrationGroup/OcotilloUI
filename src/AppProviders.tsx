import { ReactNode } from 'react'
import { QueryClient, QueryClientProvider } from '@tanstack/react-query'
import { RefineSnackbarProvider, useNotificationProvider } from '@refinedev/mui'
import { AppBreadcrumb } from '@/components/AppBreadcrumb'
import { DevtoolsProvider, DevtoolsPanel } from '@refinedev/devtools'
import { LocalizationProvider } from '@mui/x-date-pickers'
import { AdapterDayjs } from '@mui/x-date-pickers/AdapterDayjs'
import { CssBaseline, GlobalStyles } from '@mui/material'
import { Action, IResourceItem, Refine } from '@refinedev/core'
import routerProvider, {
  DocumentTitleHandler,
  UnsavedChangesNotifier,
} from '@refinedev/react-router'
import { ColorModeContextProvider } from '@/contexts'
import {
  ampDataProvider,
  authentikAuthProvider,
  ocotilloDataProvider,
  accessControlProvider,
  st2DataProvider,
  geothermalDataProvider,
  geochronologyDataProvider,
  ogcapiDataProvider,
  usgsNwisOgcapiDataProvider,
} from '@/providers'
import { resources } from '@/resources'
import { PostHogPageview } from '@/components/analytics/PostHogPageview'
import { SearchProvider } from '@/providers/search-provider'

const queryClient = new QueryClient()
const appTitle = import.meta.env.DEV
  ? 'Ocotillo (Dev)'
  : import.meta.env.VITE_APP_TITLE || 'Ocotillo'

const customTitleHandler = (options: {
  resource?: IResourceItem
  action?: Action
  params?: Record<string, string | undefined>
  pathname?: string
  autoGeneratedTitle: string
}) =>
  options.action === 'list'
    ? `${appTitle} | ${options.resource.meta.label}`
    : appTitle

export const AppProviders = ({ children }: { children: ReactNode }) => (
  <ColorModeContextProvider>
    <CssBaseline />
    <GlobalStyles styles={{ html: { WebkitFontSmoothing: 'auto' } }} />
    <RefineSnackbarProvider>
      <DevtoolsProvider>
        <Refine
          authProvider={authentikAuthProvider}
          dataProvider={{
            default: ocotilloDataProvider,
            amp: ampDataProvider,
            geochronology: geochronologyDataProvider,
            geothermal: geothermalDataProvider,
            ogcapi: ogcapiDataProvider,
            'usgs-nwis-ogcapi': usgsNwisOgcapiDataProvider,
            st2: st2DataProvider,
            ocotillo: ocotilloDataProvider,
          }}
          accessControlProvider={accessControlProvider}
          routerProvider={routerProvider}
          notificationProvider={useNotificationProvider}
          resources={resources}
          options={{
            disableTelemetry: true,
            syncWithLocation: false, // Prevents Refine from writing filter/sort/pagination state into URL query params. Navigation URLs (/well/show/123) are unaffected -- those are managed by React Router.
            warnWhenUnsavedChanges: true,
            projectId: import.meta.env.VITE_REFINE_PROJECT_ID,
            breadcrumb: <AppBreadcrumb />,
          }}
        >
          <UnsavedChangesNotifier />
          <PostHogPageview />
          <DocumentTitleHandler handler={customTitleHandler} />
          <LocalizationProvider dateAdapter={AdapterDayjs}>
            <SearchProvider>
              <QueryClientProvider client={queryClient}>
                {children}
              </QueryClientProvider>
            </SearchProvider>
          </LocalizationProvider>
        </Refine>
        <DevtoolsPanel />
      </DevtoolsProvider>
    </RefineSnackbarProvider>
  </ColorModeContextProvider>
)
